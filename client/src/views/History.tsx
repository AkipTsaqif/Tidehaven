import { useEffect, useState } from 'react';
import { getJson } from '../api.js';

interface Article {
  day: number;
  headline: string;
  body: string;
  eventIds: number[];
  generatedBy: string;
}

interface HistoryResponse {
  items: Article[];
  total: number;
}

interface EventRow {
  id: number;
  day: number;
  kind: string;
  title: string;
  visibility: string;
  importance: number;
}

export function History({ revision = 0 }: { revision?: number }) {
  const [articles, setArticles] = useState<HistoryResponse | null>(null);
  const [events, setEvents] = useState<EventRow[]>([]);
  const [search, setSearch] = useState('');
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    // Superseded requests must not overwrite a newer revision: an older response arriving last would
    // otherwise replace the fresher page. The cleanup flag drops every stale response.
    let current = true;
    const query = new URLSearchParams({ limit: '20' });
    if (search) query.set('search', search);
    Promise.all([
      getJson<HistoryResponse>(`/api/history?${query.toString()}`),
      getJson<{ items: EventRow[] }>('/api/events?limit=40'),
    ])
      .then(([history, eventPage]) => {
        if (!current) return;
        setArticles(history);
        setEvents(eventPage.items);
        setError(null);
      })
      .catch((err: Error) => {
        if (current) setError(err.message);
      });
    return () => {
      current = false;
    };
  }, [search, revision]);

  return (
    <section className="stack">
      <div className="toolbar">
        <input
          placeholder="Search the archive…"
          value={search}
          onChange={(event) => setSearch(event.target.value)}
          aria-label="Search archive"
        />
        <span className="muted">{articles?.total ?? 0} issues</span>
      </div>
      {error ? <div className="banner error">{error}</div> : null}

      <div className="grid">
        <div className="stack">
          {(articles?.items ?? []).map((article) => (
            <article className="panel" key={article.day}>
              <h2>{article.headline}</h2>
              <div className="muted small">
                day {article.day} · generated by {article.generatedBy} · {article.eventIds.length} cited events
              </div>
              <pre className="newspaper">{article.body}</pre>
            </article>
          ))}
          {(articles?.items ?? []).length === 0 ? <div className="panel muted">No issues yet.</div> : null}
        </div>

        <div className="panel">
          <h2>Latest events</h2>
          <ul className="list">
            {events.map((event) => (
              <li key={event.id}>
                <span className="mono">d{event.day}</span> {event.title}{' '}
                <span className="muted">[{event.visibility}]</span>
              </li>
            ))}
          </ul>
        </div>
      </div>
    </section>
  );
}
